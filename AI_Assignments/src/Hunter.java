public class Hunter {
    public static void main(String[] args) {
        // Start at 3, loop while greater than 0, decrease by 1 each time
        for (int i = 3; i > 0; i--) {
            System.out.println(i);
        }
        
        // Print the final message after the loop finishes
        System.out.println("Blast-off!");
    }
}